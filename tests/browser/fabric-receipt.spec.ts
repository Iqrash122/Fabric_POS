import { expect, test } from '@playwright/test';
import { readFileSync } from 'node:fs';

test.use({ timezoneId: 'UTC' });

test('USB scanner queue, saved cash change, automatic print and thermal reprint', async ({ page, context }, testInfo) => {
    test.setTimeout(90_000);
    const errors: string[] = [];
    page.on('pageerror', (error) => errors.push(error.message));
    page.on('dialog', (dialog) => dialog.accept());
    await context.addInitScript(() => {
        // Exercise automatic printing without sending a job to a physical printer.
        window.print = () => { document.documentElement.dataset.printCalls = String(Number(document.documentElement.dataset.printCalls || 0) + 1); };
    });
    const credentials = JSON.parse(readFileSync(process.env.FABRIC_TEST_CREDENTIALS!, 'utf8'));
    await page.goto('/login');
    await page.getByLabel('Email address').fill(credentials.email);
    await page.getByLabel('Password', { exact: true }).fill(credentials.password);
    await page.getByRole('button', { name: 'Log in', exact: true }).click();
    await expect(page).toHaveURL(/fabric/);
    const key = Date.now().toString();
    const name = `Receipt Cotton ${key}`;
    await page.goto('/fabric/inventory');
    await page.getByRole('button', { name: 'New product', exact: true }).click();
    let dialog = page.getByRole('dialog', { name: 'New product', exact: true });
    await dialog.getByLabel('Fabric / product name').fill(name);
    await dialog.getByLabel('SKU', { exact: true }).fill(`RC-${key}`);
    await dialog.getByLabel('Product barcode').fill(`RP-${key}`);
    await dialog.getByLabel('Default selling price').fill('200.00');
    await dialog.getByRole('button', { name: 'Save product' }).click();
    await expect(page.getByText(name, { exact: true })).toBeVisible();
    await dialog.getByRole('button', { name: 'Close New product' }).click();
    await page.goto('/fabric/pos');
    const scanner = page.getByLabel('Barcode or search');
    await expect(scanner).toBeFocused();
    await scanner.fill(`RP-${key}`);
    await scanner.press('Enter');
    await page.getByRole('button', { name: 'Add opening stock', exact: true }).click();
    dialog = page.getByRole('dialog', { name: 'Add opening stock', exact: true });
    await dialog.getByLabel('Opening quantity').fill('20.000');
    await dialog.getByLabel('Cost per meter / piece').fill('100.00');
    await dialog.getByLabel('Selling price', { exact: true }).fill('200.00');
    await dialog.getByLabel('Roll number (optional)').fill(`RR-${key}`);
    await dialog.getByLabel('Barcode (optional)').fill(`rb_${key}/01`);
    await dialog.getByLabel('Opening-stock reason').fill('Receipt test stock');
    await dialog.getByRole('button', { name: 'Record opening roll' }).click();
    await expect(dialog).not.toBeVisible();
    await page.goto('/fabric/inventory');
    const stockRow = page.locator('.fabric-card').filter({ has: page.getByRole('heading', { name: 'Individual roll inventory', exact: true }) }).locator('tbody tr').filter({ hasText: `RR-${key}` });
    const barcodeImage = stockRow.getByRole('img', { name: `Barcode rb_${key}/01`, exact: true });
    await expect(barcodeImage).toBeVisible();
    await expect.poll(() => barcodeImage.evaluate((img: HTMLImageElement) => img.complete && img.naturalWidth > 0)).toBe(true);
    const labelOpened = context.waitForEvent('page');
    await stockRow.getByRole('link', { name: 'Print label', exact: true }).click();
    const labelPage = await labelOpened;
    await expect(labelPage.locator('.label')).toContainText(name);
    await expect(labelPage.locator('.code')).toHaveText(`rb_${key}/01`);
    await labelPage.getByRole('button', { name: 'Print label', exact: true }).click();
    await expect(labelPage.locator('html')).toHaveAttribute('data-print-calls', '1');
    await labelPage.emulateMedia({ media: 'print' });
    await expect(labelPage.locator('.tools')).toBeHidden();
    expect(await labelPage.locator('.label').evaluate((el) => el.scrollHeight <= el.clientHeight && el.scrollWidth <= el.clientWidth)).toBe(true);
    await labelPage.locator('.label').screenshot({ path: testInfo.outputPath('stock-barcode-label.png') });
    const labelPdf = await page.request.get((await stockRow.getByRole('link', { name: 'PDF', exact: true }).getAttribute('href'))!);
    expect(labelPdf.headers()['content-type']).toContain('application/pdf');
    expect((await labelPdf.body()).subarray(0, 5).toString()).toBe('%PDF-');
    await labelPage.close();
    await page.goto('/fabric/pos');
    await scanner.focus();
    await page.route('**/fabric/barcode/**', async (route) => {
        await new Promise((resolve) => setTimeout(resolve, 150));
        await route.continue();
    });
    // Back-to-back keyboard-wedge scans, including the alternate Tab terminator.
    for (const terminator of ['Enter', 'Tab', 'Enter']) {
        await scanner.pressSequentially(`rb_${key}/01`, { delay: 1 });
        await scanner.press(terminator);
    }
    await expect(page.getByLabel('Quantity', { exact: true })).toHaveValue('3');
    await expect(page.locator('.pos-line')).toHaveCount(1);
    await expect(scanner).toBeFocused();
    await scanner.fill('UNKNOWN-RECEIPT-CODE');
    await scanner.press('Enter');
    await expect(page.locator('.fabric-error.compact')).toContainText('No matching');
    await expect(page.locator('.pos-line')).toHaveCount(1);
    await page.getByLabel('Quantity', { exact: true }).fill('2.5');
    await page.getByLabel('Manual discount', { exact: true }).fill('50.00');
    await page.getByLabel('Manual discount reason').fill('Counter discount');
    await page.getByLabel('Payment account 1', { exact: true }).selectOption({ label: 'Cash · cash' });
    await page.getByLabel('Paid on account 1', { exact: true }).fill('1000.00');
    const postedSale = page.waitForResponse((response) => response.headers()['x-inertia'] === 'true' && response.request().redirectedFrom()?.method() === 'POST');
    await page.getByRole('button', { name: /^Post sale/ }).click();
    const { props } = await (await postedSale).json();
    expect(props.rolls.find((roll: { barcode: string }) => roll.barcode === `rb_${key}/01`).current_qty_milli).toBe(17500);
    const sale = props.sales.find((item: { id: number }) => item.id === props.last_sale_id);
    const saleTimestamp = /(?:Z|[+-]\d{2}:\d{2})$/i.test(sale.sale_at) ? sale.sale_at : `${sale.sale_at.replace(' ', 'T')}Z`;
    expect(Math.abs(Date.now() - new Date(saleTimestamp).getTime())).toBeLessThan(65_000);
    await expect(page.locator('.pos-success-banner')).toContainText('Change: PKR 550.00');
    await expect(page.locator('.pos-line')).toHaveCount(0);
    const receipt = page.frameLocator('iframe[title="Receipt print"]');
    await expect(receipt.locator('html')).toHaveAttribute('data-print-calls', '1');
    await expect(receipt.locator('.receipt')).toContainText(name);
    const shopTime = new Date(saleTimestamp).toLocaleTimeString('en-US', { timeZone: props.business.timezone, hour: '2-digit', minute: '2-digit', hour12: true });
    await expect(receipt.locator('.receipt')).toContainText(shopTime);
    await expect(receipt.locator('.receipt')).toContainText('PKR 1,000.00');
    await expect(receipt.locator('.receipt')).toContainText('PKR 550.00');
    const href = await page.getByRole('link', { name: 'Print Thermal', exact: true }).getAttribute('href');
    const preview = await context.newPage();
    await preview.goto(href!);
    await expect(preview.locator('html')).not.toHaveAttribute('data-print-calls');
    await expect(preview.locator('.receipt')).toContainText('2.5 m');
    await preview.getByRole('button', { name: 'Print receipt', exact: true }).click();
    await expect(preview.locator('html')).toHaveAttribute('data-print-calls', '1');
    await preview.emulateMedia({ media: 'print' });
    await expect(preview.locator('.toolbar')).toBeHidden();
    const width = await preview.locator('.receipt').evaluate((el) => el.getBoundingClientRect().width);
    expect(width).toBeCloseTo(80 * 96 / 25.4, 0);
    expect(await preview.locator('.receipt').evaluate((el) => el.scrollWidth <= el.clientWidth)).toBe(true);
    await preview.locator('.receipt').screenshot({ path: testInfo.outputPath('receipt-80mm.png') });
    await preview.close();
    await page.reload();
    await expect(page.locator('iframe[title="Receipt print"]')).toHaveCount(0);
    expect(errors).toEqual([]);
});
