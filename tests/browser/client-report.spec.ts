import { expect, test } from '@playwright/test';
import { readFileSync } from 'node:fs';

test('client report: promotion total is visible before checkout and customer creation refreshes accounts', async ({ page }) => {
    page.on('dialog', dialog => dialog.accept());
    const credentials = JSON.parse(readFileSync(process.env.FABRIC_TEST_CREDENTIALS!, 'utf8'));
    await page.goto('/login');
    await page.getByLabel('Email address').fill(credentials.email);
    await page.getByLabel('Password', { exact: true }).fill(credentials.password);
    await page.getByRole('button', { name: 'Log in', exact: true }).click();
    await expect(page).toHaveURL(/fabric/);
    const key = Date.now().toString();
    await page.goto('/fabric/customers');
    await page.getByRole('button', { name: 'New customer', exact: true }).click();
    let dialog = page.getByRole('dialog', { name: 'New customer', exact: true });
    await dialog.getByLabel('Customer name').fill(`Report Customer ${key}`);
    await dialog.getByLabel('Phone', { exact: true }).fill(`0300${key.slice(-7)}`);
    await dialog.getByRole('button', { name: 'Create customer', exact: true }).click();
    await expect(page.locator('.fabric-table-wrap').getByText(`Report Customer ${key}`, { exact: true })).toBeVisible();
    await dialog.getByRole('button', { name: 'Close New customer' }).click();
    await page.goto('/fabric/inventory');
    await page.getByRole('button', { name: 'New product', exact: true }).click();
    dialog = page.getByRole('dialog', { name: 'New product', exact: true });
    const name = `Promotion Cotton ${key}`;
    await dialog.getByLabel('Fabric / product name').fill(name);
    await dialog.getByLabel('SKU', { exact: true }).fill(`PROMO-${key}`);
    await dialog.getByLabel('Default selling price').fill('1000');
    await dialog.getByRole('button', { name: 'Save product' }).click();
    await expect(page.getByText(name, { exact: true })).toBeVisible();
    await dialog.getByRole('button', { name: 'Close New product' }).click();
    await page.getByRole('button', { name: 'Opening stock', exact: true }).click();
    dialog = page.getByRole('dialog', { name: 'Opening stock', exact: true });
    await dialog.getByLabel('Product', { exact: true }).selectOption({ label: `${name} · meter` });
    await dialog.getByLabel('Opening quantity').fill('10');
    await dialog.getByLabel('Cost per meter / piece').fill('100');
    await dialog.getByLabel('Selling price', { exact: true }).fill('1000');
    await dialog.getByLabel('Barcode (optional)').fill(`PROMO-ROLL-${key}`);
    await dialog.getByLabel('Opening-stock reason').fill('Isolated report regression');
    await dialog.getByRole('button', { name: 'Record opening roll' }).click();
    await expect(page.locator('.inventory-barcode').getByText(`PROMO-ROLL-${key}`, { exact: true })).toBeVisible();
    await dialog.getByRole('button', { name: 'Close Opening stock' }).click();
    await page.goto('/fabric/promotions');
    await page.getByRole('button', { name: 'New promotion', exact: true }).click();
    dialog = page.getByRole('dialog', { name: 'New promotion', exact: true });
    await dialog.getByLabel('Name', { exact: true }).fill(`Eid20 ${key}`);
    await dialog.getByLabel('Discount %').fill('20');
    await dialog.getByLabel('Starts', { exact: true }).fill('2026-01-01T00:00');
    await dialog.getByLabel('Ends', { exact: true }).fill('2030-01-01T00:00');
    await dialog.getByLabel('Priority', { exact: true }).fill('0');
    await dialog.getByLabel('Target group').selectOption('product');
    await dialog.getByLabel('Promotion targets').selectOption({ label: name });
    await dialog.getByRole('button', { name: 'Create promotion', exact: true }).click();
    await expect(page.locator('.fabric-table-wrap').getByText(`Eid20 ${key}`, { exact: true })).toBeVisible();
    await dialog.getByRole('button', { name: 'Close New promotion' }).click();
    await page.goto('/fabric/pos');
    await page.getByLabel('Barcode or search').fill(`PROMO-ROLL-${key}`);
    await page.getByLabel('Barcode or search').press('Enter');
    await page.getByLabel('Quantity', { exact: true }).fill('3');
    await expect(page.getByRole('button', { name: 'Post sale (PKR 2,400.00)', exact: true })).toBeEnabled();
    await expect(page.getByText('Discount applied: PKR 600.00', { exact: true })).toBeVisible();
    await expect(page.getByRole('button', { name: /Exact: PKR 2,400.00/ })).toBeVisible();
});

